@pytest.mark.skipif(NODE is None, reason="needs node")
def test_inlined_kagan_gives_the_exact_textbook_numbers(tmp_path):
    _, js = build_fixture_js(tmp_path)
    kag = js[js.index("window.NOBEL_CHEM_KAGAN"):]
    script = "var window = {};\n" + kag + """
    const K = window.NOBEL_CHEM_KAGAN, f = K.eeProd || K.ee_prod;
    const out = { pie: f(0.5, 4, 0), line: [0.1, 0.5, 0.9].map((x) => f(x, 4, 1)),
                  closed: [0.1, 0.3, 0.7].map((x) => f(x, 4, 0)), bigK: f(0.2, 1e9, 0) };
    console.log(JSON.stringify(out));"""
    r = subprocess.run([NODE, "-e", script], capture_output=True, text=True, timeout=30)
    assert r.returncode == 0, r.stderr
    o = json.loads(r.stdout)
    assert o["pie"] == pytest.approx(0.8, abs=1e-12)                        # 75:25 -> 80 %
    assert o["line"] == pytest.approx([0.1, 0.5, 0.9], abs=1e-12)          # g = 1: straight line
    assert o["closed"] == pytest.approx([2 * x / (1 + x * x) for x in (0.1, 0.3, 0.7)], abs=1e-12)  # K = 4, g = 0
    assert o["bigK"] == pytest.approx(1.0, abs=1e-3)                        # K -> infinity, g = 0: ee_max


