def test_real_numbers_match_the_sources():
    # S03a / SCI p. 12; S03b / SCI p. 13; SV03; Nobel popular information (the pie)
    assert bd.SOAI_2003_PCT == [0.00005, 57, 99, 99.5]
    assert bd.REAL_RUNS["soai_2003"] | {} == {**bd.REAL_RUNS["soai_2003"], "runs": 37, "one": 19, "mirror": 18, "ee_range_pct": [15, 91]}
    assert (bd.REAL_RUNS["singleton_vo_2003"]["runs"], bd.REAL_RUNS["singleton_vo_2003"]["one"], bd.REAL_RUNS["singleton_vo_2003"]["mirror"]) == (54, 27, 27)
    assert bd.KAGAN_PIE == {"ligand": [75, 25], "catalysts_pct": [56.25, 37.5, 6.25], "effective": [90, 10], "ee_prod_pct": 80}
    # the pie is exact arithmetic: random pairs of a 3:1 mix, then the mixed pairs drop out
    a, b = 0.75, 0.25
    assert [a * a * 100, 2 * a * b * 100, b * b * 100] == bd.KAGAN_PIE["catalysts_pct"]
    assert a * a / (a * a + b * b) * 100 == 90 and (a * a - b * b) / (a * a + b * b) * 100 == 80


