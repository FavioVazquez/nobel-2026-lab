def test_exact_binomial():
    assert bd.binom_two_sided(19, 37) == 1.0 and bd.binom_two_sided(27, 54) == 1.0
    assert bd.binom_two_sided(0, 10) == pytest.approx(2 / 1024)
    assert bd.binom_two_sided(2, 10) == pytest.approx(2 * (1 + 10 + 45) / 1024)
    assert bd.binom_two_sided(5000, 10000) == pytest.approx(1.0)
    # large-n branch agrees with the exact one near the switch
    lp = bd.binom_two_sided(1950, 4000)
    assert 0.1 < lp < 0.12  # z = -1.58 -> two-sided p ~ 0.114


def test_molecules_have_the_right_hands():
    one, mirror = bd.molecule("one"), bd.molecule("mirror")
    assert (one["cid"], one["cip"]) == (5950, "S")       # L-alanine is (S)
    assert (mirror["cid"], mirror["cip"]) == (71080, "R")  # D-alanine is (R)
    # PubChem's two conformers are mirror images through the z = 0 plane (heavy atoms within 0.05 A)
    for a, b in zip(one["atoms"], mirror["atoms"]):
        if a[0] != "H":
            assert a[0] == b[0] and abs(a[1] - b[1]) < 0.05 and abs(a[2] - b[2]) < 0.05 and abs(a[3] + b[3]) < 0.05


def test_cip_rule_on_a_hand_made_centre():
    # H straight back (-z); N at 12 o'clock, acid C at 4, methyl C at 8, seen from +z: clockwise -> R
    atoms = [{"el": "C", "x": 0, "y": 0, "z": 0}, {"el": "N", "x": 0, "y": 1, "z": .3},
             {"el": "C", "x": .87, "y": -.5, "z": .3}, {"el": "C", "x": -.87, "y": -.5, "z": .3},
             {"el": "H", "x": 0, "y": 0, "z": -1}, {"el": "O", "x": 1.7, "y": -.9, "z": .3}, {"el": "O", "x": .9, "y": -1.5, "z": .3},
             {"el": "H", "x": -1.7, "y": -.9, "z": .3}]
    bonds = [[0, 1, 1], [0, 2, 1], [0, 3, 1], [0, 4, 1], [2, 5, 2], [2, 6, 1], [3, 7, 1]]
    assert bd.cip_label(atoms, bonds) == "R"
    mirrored = [dict(a, x=-a["x"]) for a in atoms]
    assert bd.cip_label(mirrored, bonds) == "S"


